#!/usr/bin/env python3
"""
Generate test PPM images (P6 binary and P3 ASCII) for edge-classify.
No external dependencies required (uses standard library only).
"""

import math
import os
import sys

def write_ppm_p6(filename, width, height, pixels):
    """Write binary PPM (P6). pixels is bytes or bytearray of size width * height * 3."""
    header = f"P6\n# Generated by Edge ML Linux OS generator\n{width} {height}\n255\n".encode("ascii")
    with open(filename, "wb") as f:
        f.write(header)
        f.write(pixels)
    print(f"Generated {filename} ({width}x{height}, P6 binary, {os.path.getsize(filename)} bytes)")

def write_ppm_p3(filename, width, height, pixels):
    """Write ASCII PPM (P3). pixels is bytes or bytearray of size width * height * 3."""
    with open(filename, "w", encoding="ascii") as f:
        f.write(f"P3\n# Generated by Edge ML Linux OS generator (ASCII)\n{width} {height}\n255\n")
        idx = 0
        for y in range(height):
            row_vals = []
            for x in range(width):
                r = pixels[idx]
                g = pixels[idx + 1]
                b = pixels[idx + 2]
                idx += 3
                row_vals.append(f"{r} {g} {b}")
            f.write("  ".join(row_vals) + "\n")
    print(f"Generated {filename} ({width}x{height}, P3 ASCII, {os.path.getsize(filename)} bytes)")

def generate_gradient_pattern(width, height):
    """Generate a rich color gradient and geometric pattern."""
    data = bytearray(width * height * 3)
    cx, cy = width / 2.0, height / 2.0
    max_radius = math.hypot(cx, cy)

    for y in range(height):
        for x in range(width):
            idx = (y * width + x) * 3
            # Radial distance
            dist = math.hypot(x - cx, y - cy)
            r_norm = dist / max_radius

            # Red: horizontal gradient + concentric waves
            r = int(127.5 * (1.0 + math.sin(x * 0.05 + y * 0.03)))
            # Green: vertical gradient
            g = int(255.0 * (y / height))
            # Blue: radial waves
            b = int(255.0 * (1.0 - r_norm))

            # Add a centered bright square
            if abs(x - cx) < width * 0.15 and abs(y - cy) < height * 0.15:
                r = min(255, r + 80)
                g = min(255, g + 80)
                b = max(0, b - 50)

            data[idx] = max(0, min(255, r))
            data[idx + 1] = max(0, min(255, g))
            data[idx + 2] = max(0, min(255, b))

    return data

def generate_color_bars(width, height):
    """Standard 8-color test bars: White, Yellow, Cyan, Green, Magenta, Red, Blue, Black."""
    colors = [
        (255, 255, 255), # White
        (255, 255,   0), # Yellow
        (  0, 255, 255), # Cyan
        (  0, 255,   0), # Green
        (255,   0, 255), # Magenta
        (255,   0,   0), # Red
        (  0,   0, 255), # Blue
        (  0,   0,   0), # Black
    ]
    data = bytearray(width * height * 3)
    bar_width = width / len(colors)

    for y in range(height):
        for x in range(width):
            bar_idx = min(int(x / bar_width), len(colors) - 1)
            color = colors[bar_idx]
            idx = (y * width + x) * 3
            data[idx] = color[0]
            data[idx + 1] = color[1]
            data[idx + 2] = color[2]

    return data

def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "rootfs/usr/share/edgeml/images"
    os.makedirs(out_dir, exist_ok=True)

    # 1. 300x200 gradient pattern (requires resize to 224x224 during inference)
    p6_data_300 = generate_gradient_pattern(300, 200)
    write_ppm_p6(os.path.join(out_dir, "sample_gradient_300x200.ppm"), 300, 200, p6_data_300)

    # 2. 224x224 color bars (native MobileNet input size)
    p6_bars_224 = generate_color_bars(224, 224)
    write_ppm_p6(os.path.join(out_dir, "sample_bars_224x224.ppm"), 224, 224, p6_bars_224)

    # 3. Small 64x64 ASCII PPM (demonstrating P3 parsing)
    p3_data_64 = generate_gradient_pattern(64, 64)
    write_ppm_p3(os.path.join(out_dir, "sample_ascii_64x64.ppm"), 64, 64, p3_data_64)

    # 4. Standard default sample link / copy: sample.ppm -> sample_gradient_300x200.ppm
    sample_default = os.path.join(out_dir, "sample.ppm")
    write_ppm_p6(sample_default, 300, 200, p6_data_300)
    print("All sample test images generated successfully.")

if __name__ == "__main__":
    main()
